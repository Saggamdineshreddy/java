package examples;

public class relationaloperators {
    public static void main(String[] args) {
        int a=10;
        int b=20;

        boolean result= a<b;
        System.out.println(result);

        boolean result1= a>b;
        System.out.println(result1);

        boolean result2= a==b;
        System.out.println(result2);
    }
}
